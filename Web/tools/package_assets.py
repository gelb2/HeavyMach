#!/usr/bin/env python3
"""Package HeavyMach web assets into several Emscripten data files.

Static hosts such as Cloudflare Pages reject files over 25 MiB, and the single
--preload-file package is about 46 MB. This script keeps the same files and the
same virtual paths (/assets/...), but splits them into packages under a size cap
and writes one loader script (hm-assets.js) that the shell loads before index.js.

  package_assets.py --packager <file_packager.py> --out <dist> --cap-mib 20 \
      <src_dir>@<virtual_dir> [...]

Writes <out>/hm-assets-<n>.data, <out>/hm-assets.js and <out>/hm-assets.json
(file count, bytes and SHA-256 per package).
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile


def collect(roots):
    files = []
    for root in roots:
        src, dst = root.rsplit("@", 1)
        for base, dirs, names in os.walk(src):
            dirs[:] = sorted(d for d in dirs if not d.startswith("."))
            for name in sorted(names):
                if name.startswith("."):
                    continue
                path = os.path.join(base, name)
                rel = os.path.relpath(path, src).replace(os.sep, "/")
                if "@" in path or "@" in rel:
                    sys.exit(f"package_assets: '@' in asset path is not supported: {path}")
                files.append((path, f"{dst}/{rel}", os.path.getsize(path)))
    return files


def split(files, cap):
    packages, current, size = [], [], 0
    for entry in files:
        if entry[2] > cap:
            sys.exit(f"package_assets: {entry[0]} is larger than the package cap")
        if current and size + entry[2] > cap:
            packages.append(current)
            current, size = [], 0
        current.append(entry)
        size += entry[2]
    if current:
        packages.append(current)
    return packages


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--packager", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--cap-mib", type=float, default=20)
    parser.add_argument("roots", nargs="+")
    args = parser.parse_args()

    os.makedirs(args.out, exist_ok=True)
    for name in os.listdir(args.out):
        if name.startswith("hm-assets"):
            os.remove(os.path.join(args.out, name))

    files = collect(args.roots)
    packages = split(files, int(args.cap_mib * 1024 * 1024))
    loaders, manifest = [], []
    with tempfile.TemporaryDirectory() as tmp:
        for index, package in enumerate(packages, 1):
            data = f"hm-assets-{index}.data"
            js = os.path.join(tmp, f"{index}.js")
            cmd = [sys.executable, args.packager, os.path.join(args.out, data), "--no-node", f"--js-output={js}", "--preload"]
            cmd += [f"{src}@{dst}" for src, dst, _ in package]
            subprocess.run(cmd, check=True, stderr=subprocess.DEVNULL)
            with open(js, encoding="utf-8") as f:
                loaders.append(f.read())
            path = os.path.join(args.out, data)
            manifest.append({"data": data, "files": len(package), "bytes": os.path.getsize(path), "sha256": sha256(path)})

    with open(os.path.join(args.out, "hm-assets.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by Web/tools/package_assets.py. Loads every asset package before index.js runs.\n")
        f.write("\n".join(loaders))
    with open(os.path.join(args.out, "hm-assets.json"), "w", encoding="utf-8") as f:
        json.dump({"files": len(files), "packages": manifest}, f, indent=2)
        f.write("\n")
    print(f"package_assets: {len(files)} files in {len(packages)} packages")


if __name__ == "__main__":
    main()
